local T = dofile(os.getenv("SERPIS_TEST_DIR") .. "/lib.lua")
serpis.keys.scheme("vim")

local families = serpis.font.list()
T.check("lists installed families", #families > 10, true)

-- A family name resolves among the installed fonts.
serpis.font.set({ mono = "Menlo", mono_size = 15, size = 16 })
T.check("font-mono set", serpis.font.get().mono, "Menlo")
T.check("mono_size applied", serpis.font.get().mono_size, 15)
T.check("size applied", serpis.font.get().size, 16)

-- Cmd-= / Cmd-+ / Cmd-- arrive as platform key events and scale both sizes.
serpis.debug.key("Equals", { "cmd" })
serpis.defer(200, function()
  T.check("cmd-= increases", serpis.font.get().mono_size, 16)
  serpis.debug.key("Plus", { "cmd", "shift" })
  serpis.defer(200, function()
    T.check("cmd-+ increases", serpis.font.get().mono_size, 17)
    serpis.debug.key("Minus", { "cmd" })
    serpis.debug.key("Minus", { "cmd" })
    serpis.defer(200, function()
      T.check("cmd-- decreases", serpis.font.get().mono_size, 15)
      T.check("ui size follows", serpis.font.get().size, 16)
      serpis.debug.key("Equals", { "cmd" })
      serpis.debug.key("0", { "cmd" })
      serpis.defer(200, function()
        T.check("cmd-0 resets to the configured size", serpis.font.get().mono_size, 15)
        -- Theme switches keep the current size.
        serpis.debug.key("Equals", { "cmd" })
        serpis.defer(200, function()
          serpis.theme.load("modus-operandi")
          T.check("theme switch keeps size", serpis.font.get().mono_size, 16)
          T.finish()
        end)
      end)
    end)
  end)
end)
